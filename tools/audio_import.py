"""Spec audio-pass 2.1 / 3.1-3.2: imports the sound bank's files from the packs on disk.

  python tools/audio_import.py --source H:/assets/audio            import every row with a missing take, a take older than its source, or no measurements
  python tools/audio_import.py --source H:/assets/audio --force    re-import every row
  python tools/audio_import.py --check                              check the committed bank against the manifest (no source needed)
  python tools/audio_import.py --manifest <file> --out <dir> ...    another manifest (tests use tests/fixtures/audio/)

For each manifest row and each of its takes: decode the pack file with ffmpeg, mix to mono, resample to 44.1 kHz, trim
leading and trailing silence, cut to the category's max length with a fade, gain it to the category's loudness target
(EBU R128 maximum momentary loudness), keep the true peak at or under the ceiling with a limiter, and write 16-bit PCM
WAV to <out>/<pack>/<id>[_<n>].wav. The measured loudness, true peak and length go back into the row's "measured", and
CREDITS.md's sound section is regenerated. Never reads a folder named do_not_include, refuses licences other than CC0 /
CC BY 3.0 / CC BY 4.0, and refuses a reserved pack's sound outside the allow-list. Needs ffmpeg on PATH. Standard
library only (run it with `python -I`).
"""
import argparse
import json
import os
import re
import subprocess
import sys
import tempfile

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
DEFAULT_MANIFEST = os.path.join(ROOT, "client-godot", "presentation", "audio", "sfx", "manifest.json")
DEFAULT_CREDITS = os.path.join(ROOT, "CREDITS.md")
ALLOWED_LICENCES = {"CC0-1.0", "CC-BY-3.0", "CC-BY-4.0"}
LICENCE_URLS = {"CC0-1.0": "https://creativecommons.org/publicdomain/zero/1.0/",
                "CC-BY-3.0": "https://creativecommons.org/licenses/by/3.0/",
                "CC-BY-4.0": "https://creativecommons.org/licenses/by/4.0/"}
FORBIDDEN_DIR = "do_not_include"
CREDITS_BEGIN = "<!-- audio: generated by tools/audio_import.py from client-godot/presentation/audio/sfx/manifest.json -->"
CREDITS_END = "<!-- /audio -->"


class Problem(Exception):
    pass


def take_path(out_dir, row, index):
    suffix = "" if len(row["takes"]) == 1 else "_%d" % (index + 1)
    return os.path.join(out_dir, row["pack"], row["id"] + suffix + ".wav")


def take_res_path(row, index):
    """The res:// path of a take (what the bank .tres points at)."""
    suffix = "" if len(row["takes"]) == 1 else "_%d" % (index + 1)
    return "res://presentation/audio/sfx/%s/%s%s.wav" % (row["pack"], row["id"], suffix)


def check_rules(manifest):
    """Licence, pack and reserved-pack rules. Returns a list of problems (strings)."""
    problems = []
    packs = manifest.get("packs", {})
    allow = set(manifest.get("reserved_allow", []))
    for name, pack in packs.items():
        if pack.get("licence") not in ALLOWED_LICENCES:
            problems.append("pack %s: licence %r is not CC0 / CC BY 3.0 / CC BY 4.0" % (name, pack.get("licence")))
        if FORBIDDEN_DIR in pack.get("folder", "").replace("\\", "/").split("/"):
            problems.append("pack %s: its folder is under %s" % (name, FORBIDDEN_DIR))
    seen = set()
    for row in manifest.get("entries", []):
        rid = row.get("id", "?")
        if rid in seen:
            problems.append("entry %s: the id is used twice" % rid)
        seen.add(rid)
        if row.get("pack") not in packs:
            problems.append("entry %s: unknown pack %r" % (rid, row.get("pack")))
            continue
        if row.get("category") not in manifest.get("targets", {}):
            problems.append("entry %s: unknown category %r" % (rid, row.get("category")))
        if not row.get("takes"):
            problems.append("entry %s: no takes" % rid)
        for take in row.get("takes", []):
            if FORBIDDEN_DIR in take.replace("\\", "/").split("/"):
                problems.append("entry %s: a take is under %s" % (rid, FORBIDDEN_DIR))
        if packs[row["pack"]].get("reserved") and rid not in allow:
            problems.append("entry %s: pack %s is reserved and this id is not in reserved_allow" % (rid, row["pack"]))
    return problems


def ffmpeg(args, capture=True):
    result = subprocess.run(["ffmpeg", "-hide_banner", "-nostats"] + args, capture_output=capture, text=True)
    if result.returncode != 0:
        raise Problem("ffmpeg failed: %s" % (result.stderr or "")[-400:])
    return result.stderr or ""


def measure(path):
    """(max momentary loudness LUFS, true peak dBTP, seconds) of a file, by ffmpeg's ebur128."""
    # Pad with silence so the 400 ms momentary window also covers a sound shorter than it (a 90 ms cursor).
    log = ffmpeg(["-v", "verbose", "-i", path, "-af", "apad=pad_dur=0.5,ebur128=peak=true:framelog=verbose", "-f", "null", "-"])
    moments = [float(v) for v in re.findall(r"\bM:\s*(-?[\d.]+)", log) if float(v) > -120]
    peak = re.findall(r"Peak:\s*(-?[\d.]+|-inf)\s*dBFS", log.split("Summary:")[-1])
    probe = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "format=duration", "-of", "csv=p=0", path],
                           capture_output=True, text=True)
    seconds = float(probe.stdout.strip() or 0)
    loud = max(moments) if moments else -120.0
    tp = float(peak[-1]) if peak and peak[-1] != "-inf" else -120.0
    return round(loud, 2), round(tp, 2), round(seconds, 3)


def convert(src, dst, max_ms, target, ceiling, sample_rate, fade_ms=None):
    """Trim, cut, fade, gain to the target and limit; writes dst. Two passes: measure, then apply the gain. A row's `fade_ms`
    sets the fade-out at the cut (default: 120 ms at most), so a long ringing tail dies away instead of stopping."""
    os.makedirs(os.path.dirname(dst), exist_ok=True)
    trim = ("silenceremove=start_periods=1:start_threshold=-60dB:start_silence=0.002,"
            "areverse,silenceremove=start_periods=1:start_threshold=-60dB:start_silence=0.01,areverse")
    with tempfile.TemporaryDirectory() as tmp:
        base = os.path.join(tmp, "base.wav")
        ffmpeg(["-y", "-i", src, "-ac", "1", "-ar", str(sample_rate), "-af", trim, "-c:a", "pcm_f32le", base])
        _, _, length = measure(base)
        cut = min(length, max_ms / 1000.0)
        if fade_ms is not None:
            fade = min(fade_ms / 1000.0, cut * 0.5) if length > cut else min(0.008, cut * 0.2)
        else:
            fade = min(0.12, cut * 0.4) if length > cut else min(0.008, cut * 0.2)
        shaped = os.path.join(tmp, "shaped.wav")
        ffmpeg(["-y", "-i", base, "-af", "atrim=0:%.4f,afade=t=out:st=%.4f:d=%.4f,afade=t=in:d=0.002" % (cut, cut - fade, fade),
                "-c:a", "pcm_f32le", shaped])
        loud, _, _ = measure(shaped)
        gain = target - loud
        # The limiter works on sample peaks; true peaks between samples run a little higher, so it limits 1 dB under the
        # ceiling. A sharp sound loses loudness to the limiter, so the gain is corrected and applied again (at most 4 passes).
        limit = 10 ** ((ceiling - 1.0) / 20.0)
        result = None
        for _ in range(4):
            ffmpeg(["-y", "-i", shaped, "-af", "volume=%.3fdB,alimiter=limit=%.4f:attack=1:release=20:level=false" % (gain, limit),
                    "-ar", str(sample_rate), "-ac", "1", "-c:a", "pcm_s16le", "-map_metadata", "-1", "-fflags", "+bitexact", dst])
            result = measure(dst)
            miss = target - result[0]
            if abs(miss) <= 0.5 or gain > 40:
                break
            gain += miss
    return result


def write_credits(manifest, path):
    used = sorted({row["pack"] for row in manifest["entries"]})
    lines = [CREDITS_BEGIN, "## Sound effects", "",
             "The game's sounds come from these packs. Every file was trimmed, converted to mono 16-bit 44.1 kHz WAV and "
             "loudness-matched (changes made by this project); nothing else was altered.", ""]
    for name in used:
        pack = manifest["packs"][name]
        lines.append("### %s" % pack["title"])
        lines.append("- Author: %s" % pack["author"])
        lines.append("- Source: %s" % pack["url"])
        lines.append("- Licence: %s (%s)" % (pack["licence"], LICENCE_URLS[pack["licence"]]))
        if pack.get("licence_note"):
            lines.append("- Note: %s" % pack["licence_note"])
        files = sorted({t for row in manifest["entries"] if row["pack"] == name for t in row["takes"]})
        by_file = pack.get("file_authors", {})
        if by_file:
            # A pack whose files have their own authors (EasyRPG): name each file's author and licence, as CC BY asks.
            lines.append("- Files used, with their authors:")
            for file in files:
                who = by_file.get(file, {})
                lines.append("  - %s: %s%s" % (file, who.get("author", "unknown"), (" (%s)" % who["url"]) if who.get("url") else ""))
        else:
            lines.append("- Files used: %s" % ", ".join(files))
        lines.append("")
    lines.append(CREDITS_END)
    block = "\n".join(lines)
    text = open(path, encoding="utf-8").read() if os.path.exists(path) else "# Credits\n\n"
    if CREDITS_BEGIN in text and CREDITS_END in text:
        text = text[:text.index(CREDITS_BEGIN)] + block + text[text.index(CREDITS_END) + len(CREDITS_END):]
    else:
        text = text.rstrip("\n") + "\n\n" + block + "\n"
    with open(path, "w", encoding="utf-8", newline="\n") as f:
        f.write(text if text.endswith("\n") else text + "\n")


def check_bank(manifest, out_dir):
    """The committed bank: every take exists, has the format, its loudness and peak are on target, lengths capped."""
    problems = []
    fmt = manifest["format"]
    tol = manifest.get("tolerance_db", 1.5)
    for row in manifest["entries"]:
        target = manifest["targets"][row["category"]]
        for i in range(len(row["takes"])):
            path = take_path(out_dir, row, i)
            if not os.path.exists(path):
                problems.append("%s: missing %s" % (row["id"], os.path.relpath(path, ROOT)))
                continue
            probe = subprocess.run(["ffprobe", "-v", "error", "-show_entries", "stream=sample_rate,channels,codec_name",
                                    "-of", "csv=p=0", path], capture_output=True, text=True).stdout.strip().split(",")
            want = ["pcm_s16le", str(fmt["sample_rate"]), str(fmt["channels"])]  # the import always writes mono
            if probe != want:
                problems.append("%s: format %s, want %s" % (row["id"], probe, want))
            loud, peak, seconds = measure(path)
            if abs(loud - target) > tol:
                problems.append("%s take %d: loudness %.1f, target %.1f (more than %.1f dB off)" % (row["id"], i + 1, loud, target, tol))
            if peak > manifest["peak_ceiling_db"] + 0.3:
                problems.append("%s take %d: peak %.1f dBTP over the ceiling" % (row["id"], i + 1, peak))
            max_ms = row.get("max_ms", manifest["max_ms"][row["category"]])  # a row may set its own, as convert() honours
            if seconds * 1000 > max_ms + 5:
                problems.append("%s take %d: %.0f ms, longer than its %d ms" % (row["id"], i + 1, seconds * 1000, max_ms))
    return problems


def main():
    parser = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    parser.add_argument("--source", help="folder holding the packs' folders (outside the repo)")
    parser.add_argument("--manifest", default=DEFAULT_MANIFEST)
    parser.add_argument("--out", help="bank folder (default: next to the manifest)")
    parser.add_argument("--credits", default=DEFAULT_CREDITS)
    parser.add_argument("--force", action="store_true")
    parser.add_argument("--check", action="store_true")
    parser.add_argument("--only", help="comma-separated ids to import")
    args = parser.parse_args()
    manifest_path = os.path.abspath(args.manifest)
    out_dir = os.path.abspath(args.out or os.path.dirname(manifest_path))
    manifest = json.load(open(manifest_path, encoding="utf-8"))
    problems = check_rules(manifest)
    if problems:
        print("\n".join("refused: " + p for p in problems))
        return 2
    if args.check:
        problems = check_bank(manifest, out_dir)
        print("\n".join(problems) if problems else "bank ok: %d entries" % len(manifest["entries"]))
        return 1 if problems else 0
    if not args.source:
        print("--source is required to import")
        return 2
    if FORBIDDEN_DIR in os.path.abspath(args.source).replace("\\", "/").split("/"):
        print("refused: the source is inside %s" % FORBIDDEN_DIR)
        return 2
    only = set(args.only.split(",")) if args.only else None
    fmt = manifest["format"]
    done = 0
    for row in manifest["entries"]:
        if only and row["id"] not in only:
            continue
        pack = manifest["packs"][row["pack"]]
        sources = [os.path.join(args.source, pack["folder"], take) for take in row["takes"]]
        for src in sources:
            if not os.path.exists(src):
                print("missing source for %s: %s" % (row["id"], src))
                return 2
        targets = [take_path(out_dir, row, i) for i in range(len(row["takes"]))]
        # A row is imported again when forced, when any take is missing or older than its source, or when its measurements do
        # not cover every take (a take added to the row, an interrupted import).
        current = (not args.force and len(row.get("measured", [])) == len(targets)
                   and all(os.path.exists(t) and os.path.getmtime(t) >= os.path.getmtime(src) for t, src in zip(targets, sources)))
        if current:
            continue
        measured = []
        for src, dst in zip(sources, targets):
            loud, peak, seconds = convert(src, dst, row.get("max_ms", manifest["max_ms"][row["category"]]),
                                          manifest["targets"][row["category"]], manifest["peak_ceiling_db"], fmt["sample_rate"],
                                          row.get("fade_ms"))
            measured.append({"loudness": loud, "peak_db": peak, "ms": int(round(seconds * 1000))})
            done += 1
        row["measured"] = measured
    with open(manifest_path, "w", encoding="utf-8", newline="\n") as f:
        json.dump(manifest, f, indent=1, ensure_ascii=False)
        f.write("\n")
    write_credits(manifest, os.path.abspath(args.credits))
    print("imported %d takes; manifest and credits updated" % done)
    problems = check_bank(manifest, out_dir)
    if problems:
        print("\n".join(problems))
        return 1
    return 0


if __name__ == "__main__":
    sys.exit(main())
