using System.Text.Json.Serialization;

namespace Rpg.Contracts.Cards;

// Spec card-collection 3.1. Wire shapes only: the pack draw, the rates and every rule live on the server (Rpg.Economy).

public static class CardKinds
{
    public const string Character = "character";
    public const string Item = "item";   // equipment is an item card
}

/// <summary>Mythic is one tier above Legendary and is only for characters; items are Common..Legendary.</summary>
public static class CardRarities
{
    public const string Common = "common";
    public const string Rare = "rare";
    public const string Epic = "epic";
    public const string Legendary = "legendary";
    public const string Mythic = "mythic";

    /// <summary>Lowest to highest; the pack draw walks the odds in this order (spec 3.4).</summary>
    public static readonly string[] Order = [Common, Rare, Epic, Legendary, Mythic];
}

/// <summary>One card of the catalog. DustValue / CraftCost are the rates in force when the response was built.</summary>
public sealed record CardDto(string Id, string Kind, string Rarity, string SetId, bool Core,
    IReadOnlyList<string> Pools, bool Retired, int DustValue, int CraftCost);

public sealed record CatalogResponse(int CatalogVersion, string CatalogHash, IReadOnlyList<CardDto> Cards);

/// <summary><c>infra/economy/card_catalog.json</c>, written by the Godot tool <c>build_card_catalog.tscn</c> (spec 2.1).</summary>
public sealed record CardCatalogFile(string CatalogHash, IReadOnlyList<CatalogFileCard> Cards);

public sealed record CatalogFileCard(string Id, string Kind, string Rarity, string SetId, bool Core, IReadOnlyList<string> Pools);

/// <summary><c>infra/economy/card_economy.json</c>: placeholder rates and packs, filled only where no row exists (spec 3.4b).</summary>
public sealed record CardEconomySeed(IReadOnlyList<CardRateRequest> Rates, IReadOnlyList<PackTypeRequest> Packs);

/// <param name="Source">pack | craft.</param>
public sealed record OwnedCardDto(string CardId, DateTimeOffset AcquiredAt, string Source, string? LockedByRunId);

/// <summary>
/// Core cards are implied (everyone owns them) and not listed in Owned. ActiveRunStatus: Active | Verifying.
/// OwnedPacks (spec pack-shop 2.3): the unopened packs, sorted by pack id, zero counts left out; an empty list when none.
/// AccountVersion (spec account-session 2.4): raised by every change to what this response shows; decisions send it back as
/// their expected account version.
/// </summary>
public sealed record CollectionResponse(IReadOnlyList<OwnedCardDto> Owned, long Gems, long Dust, long AccountVersion, string? ActiveRunId,
    string? ActiveRunStatus, IReadOnlyList<PityStateDto> Pity, IReadOnlyList<OwnedPackDto> OwnedPacks);

/// <summary>Unopened packs the player owns, per pack type (spec pack-shop 3.1; 0 counts are left out).</summary>
/// <param name="RefundHeld">Spec pack-shop 2.5: true while the refund of these packs waits for a support check (null otherwise,
/// left off the JSON).</param>
public sealed record OwnedPackDto(string PackId, int Count,
    [property: JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)] bool? RefundHeld = null);

/// <summary>The caller's counters for one pack type: packs opened since each tracked rarity last dropped.</summary>
public sealed record PityStateDto(string PackId, IReadOnlyDictionary<string, int> MissedPacks);

public sealed record PackTypeDto(string PackId, string Name, int Version, int PriceGems, int CardCount,
    IReadOnlyDictionary<string, int> OddsPer10000, IReadOnlyList<string> SetIds, IReadOnlyList<string> CardIds,
    IReadOnlyDictionary<string, int> PityPacks, IReadOnlyDictionary<string, int> FirstGuarantees, string? MinRarityPerPack);

public sealed record PackListResponse(IReadOnlyList<PackTypeDto> Packs);

/// <summary>
/// Body of open, dust and craft. The key is generated by the client per action and kept until it gets a response. Spec
/// account-session 3.1: Session is the player's current account session and ExpectedAccountVersion the account version the
/// screen showed; both required (nullable only so a missing one is told apart from 0: the endpoint refuses null with a 400).
/// </summary>
public sealed record AccountActionRequest(Guid RequestKey, long? Session, long? ExpectedAccountVersion);

/// <param name="Pity">This card was forced by a pity timer.</param>
public sealed record PackCardDto(string CardId, string Rarity, bool Duplicate, int DustGained, bool Pity);

/// <param name="DrawSeed">A decimal string (int64 is not safe as a JSON number in browsers).</param>
/// <param name="GemsSpent">0 since spec pack-shop: an open spends an owned pack, the gems were spent at the buy.</param>
/// <param name="PacksLeft">Unopened packs of this type the player still owns after this open (spec pack-shop 2.2).</param>
/// <param name="AccountVersion">Spec account-session 3.1: the account version after the open (0 on the replay of a response
/// stored before that slice).</param>
public sealed record PackOpenResponse(string OpeningId, string PackId, int PackVersion, int GemsSpent,
    IReadOnlyList<PackCardDto> Cards, long Gems, long Dust, string DrawSeed, int PacksLeft, long AccountVersion);

/// <summary>One pack type's unopened packs paid back in gems (spec pack-shop 2.5).</summary>
public sealed record PackRefundDto(string PackId, int Count, int GemsRefunded);

/// <summary>
/// POST /packs/refunds, called by the Open packs page when it opens (spec pack-shop 2.5): the refunds this call paid, so the
/// page can say where the packs went ("Your 3 Descent Packs were retired: +300 gems"); empty when nothing was due.
/// </summary>
/// <remarks>Spec account-session 2.3: no account version. A refund is not checked against the version the screen saw, so a
/// version here could include changes the screen never showed (a reward); the page reads the collection again instead.</remarks>
public sealed record PackRefundsResponse(IReadOnlyList<PackRefundDto> Refunded);

/// <summary>Body of POST /packs/refunds (spec account-session 3.1). A refund is not the player's decision: session only.</summary>
public sealed record PackRefundsRequest(long? Session);

/// <summary>
/// POST /api/v1/account/session (spec account-session 2.1, no body): the account login. Session is the player's new session
/// number, which every account action carries; Collection is the account read under the account lock as the session started
/// (Collection.AccountVersion), so it is final: no older request can commit after it.
/// </summary>
public sealed record AccountSessionResponse(long Session, CollectionResponse Collection);

/// <summary>Body of POST /packs/{packId}/buy (spec pack-shop 3.1). Count 1..Cards:MaxPacksPerBuy (10). Session and
/// ExpectedAccountVersion as on <see cref="AccountActionRequest"/> (spec account-session).</summary>
public sealed record PackBuyRequest(Guid RequestKey, int Count, long? Session, long? ExpectedAccountVersion);

/// <param name="Gems">The balance after the buy.</param>
/// <param name="Owned">Unopened packs of this type the player owns after the buy.</param>
/// <param name="AccountVersion">Spec account-session 3.1: the account version after the buy.</param>
public sealed record PackBuyResponse(string PackId, int PackVersion, int Count, int GemsSpent, long Gems, int Owned, long AccountVersion);

/// <param name="AccountVersion">Spec account-session 3.1: the account version after the dust.</param>
public sealed record DustResponse(string CardId, int DustGained, int RateVersion, long Dust, long AccountVersion);

/// <param name="AccountVersion">Spec account-session 3.1: the account version after the craft.</param>
public sealed record CraftResponse(string CardId, int DustSpent, int RateVersion, long Dust, long AccountVersion);

// Admin (economy-admin role).
/// <param name="RefundUnopened">Spec pack-shop 2.5: on a retired version only; every unopened pack is refunded in gems, and the
/// version may break the openability rule (nobody opens it). Null (left off the JSON) = false.</param>
public sealed record PackTypeRequest(string PackId, string Name, int PriceGems, int CardCount,
    IReadOnlyDictionary<string, int> OddsPer10000, IReadOnlyList<string> SetIds, bool Retired,
    IReadOnlyDictionary<string, int> PityPacks, IReadOnlyDictionary<string, int> FirstGuarantees, string? MinRarityPerPack,
    [property: JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)] bool? RefundUnopened = null);

/// <param name="RefundUnopened">True on a retire-with-refund version; null otherwise (left off the JSON).</param>
public sealed record PackTypeResponse(string PackId, string Name, int Version, int PriceGems, int CardCount,
    IReadOnlyDictionary<string, int> OddsPer10000, IReadOnlyList<string> SetIds, bool Retired,
    IReadOnlyDictionary<string, int> PityPacks, IReadOnlyDictionary<string, int> FirstGuarantees, string? MinRarityPerPack,
    DateTimeOffset EffectiveFrom, string CreatedBy,
    [property: JsonIgnore(Condition = JsonIgnoreCondition.WhenWritingNull)] bool? RefundUnopened = null);

public sealed record PackTypeListResponse(IReadOnlyList<PackTypeResponse> PackTypes);

public sealed record CardRateRequest(string Rarity, int DustValue, int CraftCost);

public sealed record CardRateResponse(string Rarity, int DustValue, int CraftCost, int Version, DateTimeOffset EffectiveFrom, string CreatedBy);

public sealed record CardRateListResponse(IReadOnlyList<CardRateResponse> Rates);
